// YouTube connector, ported from quantus-cli: a video's title, channel, description and timestamped transcript
// from a link or id. The caption link comes out of YouTube's reply, so it must point at YouTube before it is fetched.

const ID = /(?:youtube\.com\/(?:watch\?(?:.*&)?v=|shorts\/|embed\/|live\/)|youtu\.be\/)([A-Za-z0-9_-]{11})/;
const PLAYER = 'https://www.youtube.com/youtubei/v1/player?prettyPrint=false';
const CLIENT = { clientName: 'ANDROID', clientVersion: '20.10.38', androidSdkVersion: 34, hl: 'en', gl: 'US' };
const USER_AGENT = 'com.google.android.youtube/20.10.38 (Linux; U; Android 14)';
const STAMP_EVERY_SECONDS = 30;
// A stalled connection must not hang the turn (code review 10-23)
const FETCH_TIMEOUT_MS = 20_000;
const CAPTION_HOSTS = /(^|\.)(youtube\.com|googlevideo\.com)$/i;

/** The 11-character id from any link shape, or null. */
export function videoId(input) {
  const s = String(input || '').trim();
  if (/^[A-Za-z0-9_-]{11}$/.test(s)) return s;
  return ID.exec(s)?.[1] || null;
}

// &amp; last, so "&amp;lt;" becomes the text "&lt;" and is never decoded a second time
const decode = (s) =>
  s
    .replace(/<[^>]+>/g, '')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    .replace(/&amp;/g, '&');

/** Caption XML comes in two shapes: <text start dur> (legacy) and <p t d> (srv3). */
export function parseCaptions(xml) {
  const out = [];
  const legacy = /<text start="([\d.]+)"[^>]*>([\s\S]*?)<\/text>/g;
  const srv3 = /<p t="(\d+)"[^>]*>([\s\S]*?)<\/p>/g;
  let m;
  while ((m = legacy.exec(xml))) out.push({ start: Number(m[1]), text: decode(m[2]).trim() });
  if (!out.length) while ((m = srv3.exec(xml))) out.push({ start: Number(m[1]) / 1000, text: decode(m[2]).trim() });
  return out.filter((x) => x.text);
}

const stamp = (secs) => {
  const s = Math.floor(secs);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
};

export function formatTranscript(lines, { every = STAMP_EVERY_SECONDS } = {}) {
  let next = 0;
  const parts = [];
  for (const line of lines) {
    if (line.start >= next) {
      parts.push(`\n[${stamp(line.start)}] `);
      next = line.start + every;
    }
    parts.push(`${line.text} `);
  }
  return parts.join('').replace(/[ \t]+/g, ' ').trim();
}

function captionUrl(baseUrl) {
  const url = String(baseUrl ?? '').replace(/&fmt=[^&]*/, '');
  if (!URL.canParse(url)) throw new Error('not a YouTube caption link');
  const { protocol, hostname } = new URL(url);
  if (protocol !== 'https:' || !CAPTION_HOSTS.test(hostname)) throw new Error('not a YouTube caption link');
  return url;
}

/**
 * @param {string} input a YouTube link or id
 * @param {{ lang?: string, fetchImpl?: typeof fetch }} [options]
 */
export async function fetchTranscript(input, { lang = 'en', fetchImpl = fetch } = {}) {
  const id = videoId(input);
  if (!id) throw new Error(`Not a YouTube link or id: ${input}`);
  const res = await fetchImpl(PLAYER, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'User-Agent': USER_AGENT },
    body: JSON.stringify({ context: { client: CLIENT }, videoId: id }),
    signal: AbortSignal.timeout(FETCH_TIMEOUT_MS)
  });
  if (!res.ok) throw new Error(`YouTube player lookup failed (${res.status})`);
  const player = await res.json();
  const status = player.playabilityStatus?.status;
  if (status && status !== 'OK') throw new Error(`YouTube says ${status}: ${player.playabilityStatus?.reason || 'video unavailable'}`);

  const details = player.videoDetails || {};
  const tracks = player.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
  const meta = { id, url: `https://youtu.be/${id}`, title: details.title || '', channel: details.author || '', seconds: Number(details.lengthSeconds || 0), description: details.shortDescription || '' };
  if (!tracks.length) return { ...meta, transcript: '', language: null, note: 'This video has no captions.' };

  const track =
    tracks.find((t) => t.languageCode === lang && t.kind !== 'asr') ||
    tracks.find((t) => t.languageCode === lang) ||
    tracks.find((t) => t.languageCode?.startsWith(lang)) ||
    tracks[0];
  const capRes = await fetchImpl(captionUrl(track.baseUrl), { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
  if (!capRes.ok) throw new Error(`Caption download failed (${capRes.status})`);
  const lines = parseCaptions(await capRes.text());
  return { ...meta, transcript: formatTranscript(lines), language: track.languageCode, autoGenerated: track.kind === 'asr' };
}
